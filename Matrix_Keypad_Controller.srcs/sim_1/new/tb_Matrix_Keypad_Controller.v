module tb_Matrix_Keypad_Controller;

    //-------------------------------------------------
    // Testbench Signals
    //-------------------------------------------------

    reg clk;
    reg rst;
    reg [3:0] col;

    wire [3:0] row;
    wire [6:0] seg;

    //-------------------------------------------------
    // DUT
    //-------------------------------------------------

    Matrix_Keypad_Controller #(

        .SCAN_PERIOD(10)

    ) DUT (

        .clk(clk),
        .rst(rst),
        .row(row),
        .col(col),
        .seg(seg)

    );

    //-------------------------------------------------
    // Clock Generation (100 MHz)
    //-------------------------------------------------

    initial
        clk = 0;

    always #5 clk = ~clk;

    //-------------------------------------------------
    // Stimulus
    //-------------------------------------------------

    initial begin

        rst = 1;
        col = 4'b0000;

        #100;

        rst = 0;

        //-------------------------------------------------
        // Press Key '1'
        //-------------------------------------------------

        wait(row == 4'b1110);

        col = 4'b0001;

        #200;

        col = 4'b0000;

        #200;

        //-------------------------------------------------
        // Press Key '5'
        //-------------------------------------------------

        wait(row == 4'b1101);

        col = 4'b0010;

        #200;

        col = 4'b0000;

        #200;

        //-------------------------------------------------
        // Press Key '9'
        //-------------------------------------------------

        wait(row == 4'b1011);

        col = 4'b0100;

        #200;

        col = 4'b0000;

        #200;

        //-------------------------------------------------
        // Press Key 'D'
        //-------------------------------------------------

        wait(row == 4'b0111);

        col = 4'b1000;

        #200;

        col = 4'b0000;

        #500;

        $finish;

    end

endmodule